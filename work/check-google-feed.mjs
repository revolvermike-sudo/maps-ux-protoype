import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
import {places} from '../places.js';
import {googleSections,renderGoogleSections} from '../google-feed.js';
const helpers={photo:p=>'public/assets/places/'+p.id+'-0.jpg',esc:s=>String(s),count:s=>String(s),asset:s=>'public/assets/figma/'+s};
const html=renderGoogleSections(places,helpers);
const ids=[...html.matchAll(/data-google-place="([^"]+)"/g)].map(match=>match[1]);
assert.equal(ids.length,12);
assert.equal(new Set(ids).size,10);
assert.ok(ids.every(id=>places.some(p=>p.id===id)));
assert.deepEqual(places.filter(p=>p.tags.includes('fun')).map(p=>p.id),['new-holland','sevkabel']);
assert.equal(googleSections.at(-1).id,'fun');
assert.equal(googleSections.at(-1).title,'Развлечься');
assert.deepEqual(googleSections.map(section=>places.filter(p=>p.tags.includes(section.id)).length),[6,4,2]);
assert.equal((html.match(/google-tile--l/g)||[]).length,6);
assert.equal((html.match(/google-tile--m/g)||[]).length,6);
assert.equal((html.match(/data-place-id=/g)||[]).length,12);
for(const path of [...html.matchAll(/src="([^"]+)"/g)].map(match=>match[1]))assert.ok(existsSync(path),path);
console.log('PASS: 12 tiles, 10 unique existing places; entertainment matches Test 1; L/M components and assets are present.');
